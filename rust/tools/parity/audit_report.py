"""Write rust/TEST_PARITY.md: how every Python test maps to the Rust suite.

Combines the heuristic match of ``test_audit.py`` (a same-named Rust test or
most asserted literals present in Rust tests) with the manual decisions in
``test_audit_decisions.json``.

    python rust/tools/parity/audit_report.py
"""

from __future__ import annotations

import collections
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    audit = subprocess.run([sys.executable, str(HERE / "test_audit.py")], capture_output=True,
                           text=True, encoding="utf-8").stdout
    decisions = json.loads((HERE / "test_audit_decisions.json").read_text(encoding="utf-8"))
    decisions.pop("_doc", None)
    rows = []
    for line in audit.splitlines():
        m = re.match(r"(\S+)\s+\S+\s+\(\s*\d+\)\s+(\S+)::(\S+)", line)
        if not m:
            continue
        mark, file, test = m.groups()
        key = f"{file}::{test}"
        if key in decisions:
            status = decisions[key]
        elif mark == "ok":
            status = "matched: same-named Rust test or most asserted values present in Rust tests"
        else:
            status = "undecided"
        rows.append((file, test, status))
    kind = lambda status: status.split(":")[0].split(" (")[0]  # noqa: E731
    counts = collections.Counter(kind(status) for _, _, status in rows)
    lines = [
        "# Python → Rust test parity",
        "",
        "Generated by `rust/tools/parity/audit_report.py`. Every Python test in",
        "`windows/tests` is listed in one of these groups:",
        "",
        "- **matched**: a same-named Rust test exists, or most values the test asserts",
        "  appear in Rust tests (heuristic of `test_audit.py`);",
        "- **ported / existing**: checked by hand; the named Rust test covers it;",
        "- **corpus**: covered by a generated differential corpus (parser, runtime",
        "  config, server editor or helper functions) whose inputs were recorded from",
        "  the Python suite (`record_parser_inputs.py`);",
        "- **n/a**: tests QML/Qt behaviour, the Python launcher or repository build",
        "  files that the Rust client does not use;",
        "- **not ported**: no Rust test yet, with the reason.",
        "",
        "| Group | Tests |",
        "| --- | ---: |",
    ]
    for name in ("matched", "ported", "partly ported", "existing", "corpus", "n/a", "not ported", "undecided"):
        if counts.get(name):
            lines.append(f"| {name} | {counts[name]} |")
    lines.append(f"| **total** | **{len(rows)}** |")
    lines += ["", "## Differential corpora", "",
              "| Corpus | Rust test | Cases |", "| --- | --- | ---: |"]
    for fixture, test in (
        ("crates/lumen-core/tests/fixtures/parser_parity.json", "lumen-core tests/parser_parity.rs"),
        ("crates/lumen-engines/tests/fixtures/config_parity.json", "lumen-engines tests/config_parity.rs"),
        ("crates/lumen-ui/tests/fixtures/editor_parity.json", "lumen-ui tests/editor_parity.rs"),
        ("crates/lumen-core/tests/fixtures/helper_parity.json", "lumen-core tests/helper_parity.rs"),
    ):
        data = json.loads((ROOT / fixture).read_text(encoding="utf-8"))
        lines.append(f"| `{Path(fixture).name}` | {test} | {len(data['cases'])} |")
    for group in ("not ported", "partly ported", "n/a"):
        selected = [(f, t, s) for f, t, s in rows if kind(s) == group]
        if not selected:
            continue
        lines += ["", f"## {group[0].upper() + group[1:]}", ""]
        for file, test, status in selected:
            reason = status.split(":", 1)[1].strip() if ":" in status else status
            lines.append(f"- `{file}::{test}`: {reason}")
    lines += ["", "## Hand-checked mapping", "",
              "Ported, existing and corpus decisions are in",
              "`rust/tools/parity/test_audit_decisions.json`.", ""]
    (ROOT / "TEST_PARITY.md").write_text("\n".join(lines), encoding="utf-8")
    print(dict(counts), len(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
